def emoji(name_or_key: str, color: str = "dark_blue", fallback: Optional[str] = None) -> str:
    """
    Возвращает HTML-тег кастомного эмодзи для Telegram.
    
    Внутри <tg-emoji> ВСЕГДА должен быть валидный символ эмодзи (Unicode), 
    иначе Telegram возвращает ошибку ENTITY_TEXT_INVALID.
    """
    char = fallback or EMOJI_UNICODE_MAP.get(name_or_key, name_or_key)
    
    # Сначала проверяем в специальном словаре
    if name_or_key in SPECIAL:
        emoji_id = SPECIAL[name_or_key]
        return f'<tg-emoji emoji-id="{emoji_id}">{char}</tg-emoji>'
    
    palette = PALETTES.get(color, DARK_BLUE)
    emoji_id = palette.get(name_or_key) or DARK_BLUE.get(name_or_key)
    
    if not emoji_id:
        return char
    
    return f'<tg-emoji emoji-id="{emoji_id}">{char}</tg-emoji>'


def num_emoji(num: int, color: str = "dark_blue") -> str:
    """
    Возвращает кастомный эмодзи цифры от 0 до 9, а для 10 — комбинацию 1 и 0.
    """
    if 0 <= num <= 9:
        return emoji(str(num), color=color, fallback=f"{num}️⃣")
    elif num == 10:
        return f"{emoji('1', color=color, fallback='1️⃣')}{emoji('0', color=color, fallback='0️⃣')}"
    return f"{num}."



def combo_emojis(combo_name: str) -> str:
    """
    Возвращает строку с комбинацией кастомных эмодзи.
    """
    ids = COMBOS.get(combo_name, [])
    if combo_name == "last_call":
        fallback_char = "📞"
    else:
        fallback_char = "📢"
    return "".join(f'<tg-emoji emoji-id="{eid}">{fallback_char}</tg-emoji>' for eid in ids)
